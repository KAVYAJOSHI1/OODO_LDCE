@register.simple_tag
def icon(name, size=18, css_class=""):
    """Render an inline SVG icon by name. Unknown names render nothing."""
    body = _ICONS.get(name)
    if not body:
        return ""
    return mark_safe(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" class="gt-icon {css_class}" '
        f'style="display:inline-block;vertical-align:-3px;flex-shrink:0;">{body}</svg>'
    )
