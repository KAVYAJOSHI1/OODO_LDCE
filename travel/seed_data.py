def seed_demo_trip(stdout=None, start_date=None):
    """Build the fully planned demo trip described in the architecture doc.

    Creates (or reuses) the demo user, wipes any previous demo trip of the same
    name so the demo is repeatable, then lays out stops, dates, activities and
    a couple of loose expenses.

    Returns:
        The Trip instance.
    """
    from django.contrib.auth.models import User

    from travel.models import Activity, City, Trip
    from travel.services import BudgetService, ItineraryService

    spec = DEMO_TRIP

    user, created = User.objects.get_or_create(
        username=spec['username'],
        defaults={
            'email': spec['email'],
            'first_name': spec['first_name'],
            'last_name': spec['last_name'],
        },
    )
    if created:
        user.set_password(spec['password'])
        user.save()
        _write(stdout, 'Created demo user %s' % spec['username'])

    # Rebuild from scratch so the demo always looks the same.
    Trip.objects.filter(user=user, name=spec['trip_name']).delete()

    if start_date is None:
        # Comfortably in the future so the trip shows as upcoming.
        start_date = date.today() + timedelta(days=30)

    total_nights = sum(stop[1] for stop in spec['stops'])

    trip = ItineraryService.create_trip(
        user=user,
        name=spec['trip_name'],
        description=spec['description'],
        start_date=start_date,
        end_date=start_date + timedelta(days=total_nights),
        budget=spec['budget'],
        travelers=spec['travelers'],
    )
    trip.status = 'upcoming'
    trip.is_public = True
    trip.save(update_fields=['status', 'is_public'])

    cursor = start_date
    for city_name, nights, mode, transport_cost, hotel, rate in spec['stops']:
        city = City.objects.filter(name=city_name).first()
        if city is None:
            _write(stdout, '  ! demo city %s missing, run the seeder first' % city_name)
            continue

        stop = ItineraryService.add_stop_to_trip(
            trip,
            city_id=city.id,
            arrival_date=cursor,
            departure_date=cursor + timedelta(days=nights),
            accommodation_name=hotel,
            accommodation_cost=rate,
            transport_mode=mode,
            transport_cost=transport_cost,
        )

        # Spread the stop's activities one per day from the arrival date.
        for offset, activity_name in enumerate(spec['activities'].get(city_name, [])):
            activity = Activity.objects.filter(city=city, name=activity_name).first()
            if activity is None:
                _write(stdout, '  ! demo activity missing: %s' % activity_name)
                continue
            ItineraryService.add_activity_to_stop(
                stop.id,
                activity_id=activity.id,
                scheduled_date=cursor + timedelta(days=min(offset, nights)),
                scheduled_time=DEMO_TIMES[offset % len(DEMO_TIMES)],
            )

        cursor = stop.departure_date

    for category, description, amount in spec['expenses']:
        BudgetService.add_expense(
            trip.id,
            category=category,
            description=description,
            amount=amount,
            date=start_date,
        )

    _write(stdout, 'Demo trip built: %d stops, total %s %.2f' % (
        trip.stops.count(), trip.currency, trip.get_total_cost()))
    return trip


