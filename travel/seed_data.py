def _write(stdout, message):
    if stdout is not None:
        stdout.write(message)


def seed_data(stdout=None):
    """Load activity types, cities and activities into the database.

    Idempotent - re-running it tops up anything missing instead of duplicating.

    Returns:
        dict with the counts that now exist: activity_types, cities, activities.
    """
    from travel.models import Activity, ActivityType, City

    _write(stdout, 'Creating activity types...')
    for at_data in ACTIVITY_TYPES:
        ActivityType.objects.get_or_create(
            name=at_data['name'],
            defaults={'icon': at_data['icon']},
        )

    _write(stdout, 'Creating cities...')
    city_objects = {}
    for city_data in CITIES_DATA:
        city, created = City.objects.get_or_create(
            name=city_data['name'],
            country=city_data['country'],
            defaults={
                'description': city_data.get('description', ''),
                'cost_index': city_data.get('cost_index', 3),
                'popularity': city_data.get('popularity', 50),
                'avg_hotel_cost': city_data.get('avg_hotel_cost', 50.00),
                'avg_meal_cost': city_data.get('avg_meal_cost', 15.00),
                'avg_transport_cost': city_data.get('avg_transport_cost', 10.00),
                'latitude': city_data.get('latitude'),
                'longitude': city_data.get('longitude'),
                'image_url': city_data.get('image_url'),
            },
        )
        city_objects[city.name] = city
        if created:
            _write(stdout, '  + %s, %s' % (city.name, city.country))

    _write(stdout, 'Creating activities...')
    types_by_name = {t.name: t for t in ActivityType.objects.all()}

    for city_name, activities in ACTIVITIES_DATA.items():
        city = city_objects.get(city_name)
        if city is None:
            _write(stdout, '  ! skipping activities for unknown city %s' % city_name)
            continue

        for act_data in activities:
            Activity.objects.get_or_create(
                name=act_data['name'],
                city=city,
                defaults={
                    'activity_type': types_by_name.get(act_data.get('activity_type')),
                    'description': act_data.get('description', ''),
                    'cost': act_data.get('cost', 0.00),
                    'duration_hours': act_data.get('duration_hours', 2.0),
                    'rating': act_data.get('rating', 4.0),
                    'popularity': act_data.get('popularity', 50),
                    'best_time': act_data.get('best_time'),
                },
            )

    stats = {
        'activity_types': ActivityType.objects.count(),
        'cities': City.objects.count(),
        'activities': Activity.objects.count(),
    }
    _write(stdout, 'Seeding complete.')
    return stats


